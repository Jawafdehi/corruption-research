// The /highlights "headline findings" list shows the same 16 findings as the home page, in
// the same words and both languages. This runs the home page's own data layers (findings.js
// → copy.js → ne.js → evidence.js, exactly as the browser loads them) and writes the result
// for the React page, so a correction made for the home page reaches /highlights too.
//
//   node scripts/home_findings_for_highlights.mjs   (run by `npm run home:data`)
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HOME = path.join(SITE, "public/home");
const OUT = path.join(SITE, "src/data/home-findings.generated.json");

const ctx = { window: {} };
ctx.window.window = ctx.window;
vm.createContext(ctx);
for (const f of ["findings.js", "copy.js", "ne.js", "evidence.js"]) {
  vm.runInContext(fs.readFileSync(path.join(HOME, f), "utf8"), ctx, { filename: f });
}
const { JW, JW_COPY_ERRORS } = ctx.window;
if (JW_COPY_ERRORS && JW_COPY_ERRORS.length) {
  throw new Error(`home copy layer reports errors:\n${JW_COPY_ERRORS.join("\n")}`);
}

const findings = {};
for (const f of JW.findings) {
  if (!f.explain_ne) throw new Error(`${f.key}: no Nepali explanation`);
  findings[f.key] = {
    headline: { en: f.headline.en, ne: f.headline.ne },
    explain: { en: f.explain, ne: f.explain_ne },
    caveat: f.caveat ? { en: f.caveat.en, ne: f.caveat.ne } : null,
  };
}
const gap = Object.fromEntries(Object.entries(JW.gap).map(([k, g]) => [k, { en: g.en, ne: g.ne }]));

fs.writeFileSync(
  OUT,
  JSON.stringify({ _about: "Generated by scripts/home_findings_for_highlights.mjs from public/home/*.js. Do not edit by hand.", gap, findings }, null, 1) + "\n",
);
console.log(`home_findings_for_highlights: ${Object.keys(findings).length} findings -> ${path.relative(SITE, OUT)}`);
