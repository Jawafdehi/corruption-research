#!/usr/bin/env bash
# Pull the launch home page ("/") in from the design mockup and regenerate its data.
#
#   site/scripts/sync-home.sh [OPTIONS_DIR]
#
# OPTIONS_DIR defaults to the design workspace's options/ folder. Nothing there is
# modified: files are only read and copied.
#
#   options/7-final/{app.css,app.js,ui.js,copy.js}  -> site/public/home/
#   options/shared/base.css                         -> site/public/home/base.css
#   options/shared/brand/*.svg                      -> site/public/home/brand/
#   options/7-final/index.html  <body> markup        -> site/src/home/markup.generated.ts
#   options/shared/build_data.py (patched to read     -> site/scripts/home_build_data.py
#     this checkout's site/src/data/*.json, not `git show`)
#
# "../shared/" asset paths are rewritten to "/home/". Then home_build_data.py writes
# site/public/home/findings.js from this checkout's own data. `npm run build` reruns
# that last step, so the home page's figures always match the JSON it ships with.
set -euo pipefail

SITE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OPT="${1:-/home/julius/Desktop/jawafdehi-meta/work/2026-11-08-research-site-design/options}"
SRC="$OPT/7-final"
SH="$OPT/shared"
OUT="$SITE/public/home"

for f in "$SRC/index.html" "$SRC/app.css" "$SRC/app.js" "$SRC/ui.js" "$SRC/copy.js" "$SRC/ne.js" "$SRC/header.js" "$SRC/header.css" "$SH/base.css" "$SH/build_data.py"; do
  [[ -f "$f" ]] || { echo "sync-home: missing $f" >&2; exit 1; }
done

mkdir -p "$OUT/brand" "$SITE/src/home"

rewrite() { sed -e 's#\.\./shared/#/home/#g' "$1" > "$2"; }
for f in app.css app.js ui.js copy.js ne.js evidence.js header.js header.css; do rewrite "$SRC/$f" "$OUT/$f"; done
# The site header and footer (header.js / header.css) are one component for every page: the
# home page loads them from public/home/, the report pages import the same files from src/home/.
cp "$SRC/header.js" "$SITE/src/home/site-header.js"
cp "$SRC/header.css" "$SITE/src/home/site-header.css"
rewrite "$SH/base.css" "$OUT/base.css"
cp "$SH"/brand/*.svg "$OUT/brand/"
# The CIAA's 36th annual report (2082/83) figures, extracted from its summary (ciaa-2082-83/).
# home_build_data.py reads them from src/data/ciaa-2082-83.json.
CIAA_NEW="$OPT/../ciaa-2082-83/figures-2082-83.json"
[[ -f "$CIAA_NEW" ]] && cp "$CIAA_NEW" "$SITE/src/data/ciaa-2082-83.json"

python3 - "$SRC/index.html" "$SH/build_data.py" "$SITE" <<'PY'
import hashlib, json, re, sys
from pathlib import Path

index, build, site = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])

# 1. The page's <body> markup, minus the <script> tags (the site loads those itself).
html = index.read_text(encoding="utf-8")
m = re.search(r"<body[^>]*>(.*)</body>", html, re.S)
assert m, "no <body> in index.html"
body = re.sub(r"<script\b[^>]*>.*?</script>\s*", "", m.group(1), flags=re.S).strip()
body = body.replace("../shared/", "/home/")
for needed in ("data-sitehead", 'id="main"', "data-brandfoot", 'id="bar"', 'id="live"', 'id="app"'):
    assert needed in body, f"index.html body lost {needed}; update site/src/home/mount.ts"
(site / "src/home/markup.generated.ts").write_text(
    "// Generated by scripts/sync-home.sh from options/7-final/index.html. Do not edit.\n"
    f"export const HOME_MARKUP = {json.dumps(body, ensure_ascii=False)};\n",
    encoding="utf-8",
)

# 2. build_data.py, pointed at this checkout's files instead of `git show <commit>`.
src = build.read_text(encoding="utf-8")
patches = [
    (r'REPO = Path\("[^"]*"\)', 'REPO = Path(__file__).resolve().parents[2]  # repo root (site/scripts/..)'),
    # The last commit that touched the two data files: stable across unrelated commits.
    (r'COMMIT = "[^"]*"', 'COMMIT = subprocess.run(["git", "-C", str(REPO), "log", "-1", "--format=%h", "--", "site/src/data/headline-findings.json", "site/src/data/report.generated.json"], capture_output=True, text=True).stdout.strip() or "working-tree"'),
    (r'def show\(path\):\n(?:    .*\n)+?    return json\.loads\(out\)\n',
     'def show(path):\n    # Patched by sync-home.sh: read the checked-out file, not `git show`.\n    return json.loads((REPO / path).read_text(encoding="utf-8"))\n'),
    (r'\(HERE / "findings\.js"\)\.write_text', '(REPO / "site/public/home/findings.js").write_text'),
]
for pat, rep in patches:
    src, n = re.subn(pat, lambda _m, r=rep: r, src, count=1)
    assert n == 1, f"build_data.py patch did not apply: {pat}"
assert src.index("import subprocess") < src.index("COMMIT =") and src.index("REPO =") < src.index("COMMIT =")
src = "# Copied from options/shared/build_data.py by scripts/sync-home.sh and patched. Do not edit.\n" + src
(site / "scripts/home_build_data.py").write_text(src, encoding="utf-8")

# 3. A version stamp, so browsers fetch new copies of /home/* after a sync.
h = hashlib.sha256()
for p in sorted((site / "public/home").rglob("*")):
    if p.is_file() and p.name != "findings.js":
        h.update(p.read_bytes())
h.update(body.encode())
(site / "src/home/version.generated.ts").write_text(
    "// Generated by scripts/sync-home.sh. Do not edit.\n"
    f'export const HOME_VERSION = "{h.hexdigest()[:10]}";\n',
    encoding="utf-8",
)
PY

python3 "$SITE/scripts/home_build_data.py"
echo "sync-home: copied 7-final into $OUT and regenerated findings.js"

# The no-JavaScript fallback (generated in the mockup from the same data) also goes into the
# site's own index.html, which is what a reader without JavaScript actually gets.
python3 - "$SRC/index.html" "$SITE/index.html" <<'PY'
import re, sys
src, dst = sys.argv[1], sys.argv[2]
m = re.search(r"<noscript>.*?</noscript>", open(src, encoding="utf8").read(), re.S)
if not m: sys.exit("sync-home: no <noscript> in the mockup (run node test/gen-noscript.mjs)")
html = open(dst, encoding="utf8").read()
block = "<!--noscript-->" + m.group(0) + "<!--/noscript-->"
html = re.sub(r"<!--noscript-->.*?<!--/noscript-->", lambda _: block, html, flags=re.S) if "<!--noscript-->" in html else html.replace('<div id="root"></div>', '<div id="root"></div>\n    ' + block)
open(dst, "w", encoding="utf8").write(html)
print("sync-home: no-JavaScript fallback written into index.html")
PY
